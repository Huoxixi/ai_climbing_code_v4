"""Local knowledge checks and retrieval. No network, model calls, or private data."""
from __future__ import annotations

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlparse

DEFAULT_ROOT = Path(__file__).resolve().parents[4] / "docs" / "bouldering-knowledge"
GENERATED = "<!-- Generated by boulder-knowledge/kb.py; edit JSON sources instead. -->"
BASIS = {"source_summary": "来源摘要", "conditional_transfer": "有条件迁移",
         "teaching_hypothesis": "教学假设", "product_rule": "项目约定"}
STOP_TERMS = {"这是什么", "这是", "是什", "什么", "如何", "怎么", "怎样", "为何", "是否", "问题",
              "what", "is", "the", "a", "an", "why", "how", "does", "do", "i", "it", "and", "or",
              "my", "to", "can", "should", "when", "are", "this", "that"}
# These describe a request type, not which climbing topic is supported.
GENERAL_TERMS = {"训练", "练习", "training", "practice"}
GENERAL_TERMS |= {"实际", "一样", "情况", "就是", "更好", "好吗", "不是", "是不", "是同", "同一", "一个",
                  "这种", "做法", "一定", "定要", "要把", "可以", "需要", "什么", "怎么", "确认", "记录",
                  "之后", "了吗", "能确", "同种", "这一", "看得", "得到", "得更"}


class InvalidKnowledge(ValueError):
    pass


def require(ok, message):
    if not ok:
        raise InvalidKnowledge(message)


def text_field(obj, key, where):
    require(isinstance(obj, dict), f"{where}: expected object")
    value = obj.get(key)
    require(isinstance(value, str) and bool(value.strip()), f"{where}: missing text {key}")
    return value


def strings(obj, key, where, nonempty=True):
    value = obj.get(key)
    require(isinstance(value, list) and (bool(value) or not nonempty), f"{where}: invalid list {key}")
    require(all(isinstance(x, str) and x.strip() for x in value), f"{where}: invalid strings {key}")
    require(len(value) == len(set(value)), f"{where}: duplicate {key}")
    return value


def rows(obj, key, where):
    require(isinstance(obj, dict), f"{where}: expected object")
    value = obj.get(key)
    require(isinstance(value, list), f"{where}: invalid list {key}")
    require(all(isinstance(x, dict) for x in value), f"{where}: invalid objects {key}")
    return value


def load_json(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise InvalidKnowledge(f"{path.name}: {exc}") from exc


def safe_path(root, relative):
    target = (root / relative).resolve()
    require(target.is_relative_to(root.resolve()), f"path outside knowledge directory: {relative}")
    return target


def load_library(root):
    root = root.resolve()
    source_doc = load_json(safe_path(root, "sources.json"))
    sources = rows(source_doc, "sources", "sources.json")
    require(source_doc.get("schema_version") == 1, "sources.json: unsupported schema")
    state = load_json(safe_path(root, "state.json"))
    require(isinstance(state, dict) and state.get("schema_version") == 1, "state.json: unsupported schema")
    unit_dir = safe_path(root, "units")
    require(unit_dir.is_dir(), "units directory missing")
    units = []
    for path in sorted(unit_dir.glob("*.json")):
        safe_path(root, str(path.relative_to(root)))
        unit = load_json(path)
        require(isinstance(unit, dict) and unit.get("id") == path.stem, f"{path.name}: filename/ID mismatch")
        units.append(unit)
    return {"root": root, "sources": sources, "units": units, "state": state}


def validate(lib):
    sources, evidence = {}, {}
    for source in lib["sources"]:
        sid = text_field(source, "id", "source")
        require(sid not in sources, f"duplicate source {sid}")
        sources[sid] = source
        for key in ("title", "author", "url", "published", "accessed", "scope", "limitations"):
            text_field(source, key, sid)
        url = urlparse(source["url"])
        require(url.scheme in {"https", "http"} and bool(url.netloc), f"{sid}: invalid URL")
        require(source.get("source_type") in {"coaching", "federation", "research"}, f"{sid}: invalid source_type")
        require(source.get("access_status") in {"located", "section_read", "full_text_read"}, f"{sid}: invalid access_status")
        cards = rows(source, "evidence", sid)
        require(bool(cards), f"{sid}: no evidence cards")
        for card in cards:
            eid = text_field(card, "id", sid)
            require(eid not in evidence, f"duplicate evidence {eid}")
            for key in ("locator", "supports", "limits"):
                text_field(card, key, eid)
            evidence[eid] = (source, card)

    units = {}
    for unit in lib["units"]:
        uid = text_field(unit, "id", "unit")
        require(re.fullmatch(r"KB-[A-Z]+-\d{3}", uid) is not None, f"{uid}: invalid ID")
        require(uid not in units, f"duplicate unit {uid}")
        units[uid] = unit
        require(unit.get("schema_version") == 1, f"{uid}: unsupported schema")
        require(type(unit.get("version")) is int and unit["version"] > 0, f"{uid}: invalid version")
        for key in ("batch_id", "title"):
            text_field(unit, key, uid)
        for key in ("aliases", "questions", "tags", "stage_tags"):
            strings(unit, key, uid)
        for key in ("action_codes", "related_units", "gaps"):
            strings(unit, key, uid, False)
        ctx = unit.get("context")
        require(isinstance(ctx, dict) and ctx.get("activity") == "indoor_bouldering", f"{uid}: unsupported activity")
        for key in ("applies_if", "exclusions"):
            strings(ctx, key, uid)
        claims = rows(unit, "claims", uid)
        require(bool(claims), f"{uid}: no claims")
        claim_ids, grounded = set(), False
        for claim in claims:
            cid = text_field(claim, "id", uid)
            require(cid not in claim_ids, f"{uid}: duplicate claim {cid}")
            claim_ids.add(cid)
            text_field(claim, "statement", uid)
            basis = claim.get("basis")
            require(basis in BASIS, f"{uid}/{cid}: invalid basis")
            refs = strings(claim, "evidence_ids", uid, False)
            if basis in {"source_summary", "conditional_transfer"}:
                require(bool(refs), f"{uid}/{cid}: sourced claim needs evidence")
                grounded = True
            if basis == "conditional_transfer":
                text_field(claim, "transfer_note", uid)
            for eid in refs:
                require(eid in evidence, f"{uid}/{cid}: missing evidence {eid}")
                require(evidence[eid][0]["access_status"] != "located", f"{uid}/{cid}: unread source {eid}")
        require(grounded, f"{uid}: no grounded claim")
        obs = unit.get("observation")
        require(isinstance(obs, dict), f"{uid}: observation missing")
        for key in ("required_views", "events", "unknowns", "cannot_infer"):
            strings(obs, key, uid)
        step = unit.get("next_step")
        require(isinstance(step, dict) and step.get("kind") == "review_only", f"{uid}: unsupported next_step")
        text_field(step, "text", uid)
        strings(step, "conditions", uid)
        strings(step, "compare", uid)
        examples = rows(unit, "examples", uid)
        require(len(examples) >= 2, f"{uid}: need typical and counter/unknown example")
        for example in examples:
            require(example.get("kind") == "constructed", f"{uid}: v1 examples must be explicitly constructed")
            for key in ("scenario", "allowed", "disallowed"):
                text_field(example, key, uid)
        review = unit.get("review")
        require(isinstance(review, dict), f"{uid}: review missing")
        require(review.get("content") in {"draft", "ai_source_checked"}, f"{uid}: unsupported content review")
        require(review.get("professional") == "pending", f"{uid}: professional review requires a new evidence contract")
        require(review.get("video_validation") == "not_started", f"{uid}: video validation requires a new evidence contract")
        require(review.get("automatic_use") is False, f"{uid}: automatic advice disabled in v1")

    for uid, unit in units.items():
        for peer in unit["related_units"]:
            require(peer in units and peer != uid, f"{uid}: invalid related unit {peer}")
    state = lib["state"]
    text_field(state, "updated", "state")
    log = safe_path(lib["root"], text_field(state, "last_run", "state"))
    require(log.is_file() and log.suffix == ".md", "state: last_run file missing")
    batches, listed = {}, set()
    for batch in rows(state, "batches", "state"):
        bid = text_field(batch, "id", "batch")
        require(bid not in batches, f"duplicate batch {bid}")
        batches[bid] = batch
        text_field(batch, "topic", bid)
        text_field(batch, "next_action", bid)
        require(batch.get("status") in {"pending", "in_progress", "authored"}, f"{bid}: invalid status")
        ids = strings(batch, "unit_ids", bid, batch["status"] == "authored")
        for uid in ids:
            require(uid in units, f"{bid}: missing unit {uid}")
            require(uid not in listed and units[uid]["batch_id"] == bid, f"{bid}: unit assigned twice or to wrong batch {uid}")
            listed.add(uid)
    require(listed == set(units), "state: some units are not assigned to their batch")
    return {"units": len(units), "sources": len(sources), "evidence_cards": len(evidence),
            "automatic_advice_units": 0, "scope": "structure_and_references_only"}


def terms(text):
    text = text.casefold()
    words = set(re.findall(r"[a-z0-9]+", text))
    for segment in re.findall(r"[\u4e00-\u9fff]+", text):
        words.update(segment[i:i + 2] for i in range(len(segment) - 1))
    return words - STOP_TERMS


def name_matches(name, query):
    """Match Latin names as words, allowing common inflections, not substrings."""
    if len(name) < 2:
        return False
    if re.fullmatch(r"[A-Za-z -]+", name):
        words = re.findall(r"[a-z]+", name.casefold())
        if not words:
            return False
        final = words[-1]
        suffix = r"(?:s|es|ing|" + re.escape(final[-1]) + r"ing)?"
        pattern = r"\b" + r"[\s-]+".join(re.escape(w) for w in words) + suffix + r"\b"
        return re.search(pattern, query.casefold()) is not None
    return name.casefold() in query.casefold()


def search(lib, query, purpose="learn", limit=5):
    if purpose == "video":
        return []
    qterms = terms(query)
    if not qterms:
        return []
    ranked = []
    for unit in lib["units"]:
        if unit["review"]["content"] != "ai_source_checked":
            continue
        names = [unit["title"], *unit["aliases"], *unit["tags"]]
        topic_terms = terms(" ".join(names)) - GENERAL_TERMS
        common = qterms & terms(" ".join([*names, *unit["questions"]])) - GENERAL_TERMS
        matched_names = [name for name in names if name_matches(name, query)]
        if not matched_names and not common:
            continue
        # An isolated broad fragment in a question is not enough evidence of topic.
        question_match = any(len(common & (qt := terms(q) - GENERAL_TERMS)) >= 3
                             and len(common & qt) / max(1, len(qt)) >= .5
                             for q in unit["questions"])
        if not matched_names and len(qterms & topic_terms) < 2 and not question_match:
            continue
        score = len(common) + 3 * len(matched_names)
        if score:
            ranked.append({"id": unit["id"], "title": unit["title"], "score": score,
                           "matched_terms": sorted(common), "matched_names": matched_names,
                           "use": "knowledge_candidate_only",
                           "file": f"units/{unit['id']}.json", "context": unit["context"]})
    return sorted(ranked, key=lambda x: (-x["score"], x["id"]))[:limit]


def status(lib):
    state = lib["state"]
    next_batch = next((b for b in state["batches"] if b["status"] != "authored"), None)
    return {"units": len(lib["units"]), "sources": len(lib["sources"]),
            "batches": dict(Counter(b["status"] for b in state["batches"])),
            "next_batch": next_batch, "last_run": state["last_run"],
            "content_review": dict(Counter(u["review"]["content"] for u in lib["units"])),
            "automatic_advice_units": 0}


def handbook(lib):
    evidence = {e["id"]: (s, e) for s in lib["sources"] for e in s["evidence"]}
    out = [GENERATED, "", "# 抱石知识手册", "",
           "当前知识用于解释与人工复盘辅助。专业复核待完成；真实视频未验证；自动视频建议未启用。", "",
           "来源主张附直接链接与定位。以下视频观察、下一步和例子为项目设计，尚未验证效果。", "",
           "[使用与续做](README.md) · [进度](state.json)", "", "## 目录", ""]
    for u in lib["units"]:
        out.append(f"- [{u['id']} · {u['title']}](#{u['id'].lower()})")
    for u in lib["units"]:
        content_label = {"draft": "草稿", "ai_source_checked": "AI 已核对来源段落"}[u["review"]["content"]]
        out.extend(["", f'<a id="{u["id"].lower()}"></a>', "", f"## {u['id']} · {u['title']}", "",
                    f"别名：{'、'.join(u['aliases'])}。版本：{u['version']}。内容状态：{content_label}。", "",
                    "### 要回答的问题", "", *[f"- {q}" for q in u["questions"]], "", "### 技术与依据", ""])
        for c in u["claims"]:
            refs = []
            for eid in c["evidence_ids"]:
                source, card = evidence[eid]
                refs.append(f"[{source['title']}]({source['url']})（{eid}；{card['locator']}）")
            out.append(f"- {BASIS[c['basis']]}：{c['statement']}" + (" 依据：" + "；".join(refs) if refs else ""))
            if c.get("transfer_note"):
                out.append(f"  迁移条件：{c['transfer_note']}")
        for title, values in [("适用条件", u["context"]["applies_if"]), ("不适用或需另查", u["context"]["exclusions"]),
                              ("必须看清", u["observation"]["required_views"]), ("视频观察", u["observation"]["events"]),
                              ("保留未知", u["observation"]["unknowns"]), ("不能直接推断", u["observation"]["cannot_infer"])]:
            out.extend(["", f"### {title}", "", *[f"- {v}" for v in values]])
        out.extend(["", "### 下一步：辅助复核", "", u["next_step"]["text"], "",
                    *[f"- 条件：{v}" for v in u["next_step"]["conditions"]],
                    *[f"- 比较：{v}" for v in u["next_step"]["compare"]], "", "### 构造例与反例", ""])
        for e in u["examples"]:
            out.extend([f"- 情境：{e['scenario']}", f"  可说：{e['allowed']}", f"  不可说：{e['disallowed']}"])
        out.extend(["", "### 后续缺口", "", *[f"- {v}" for v in u["gaps"]]])
    out.extend(["", "## 来源台账", ""])
    for s in lib["sources"]:
        type_label = {"coaching": "机构教学", "federation": "协会框架", "research": "研究论文"}[s["source_type"]]
        access_label = {"located": "仅定位", "section_read": "已读所引段落", "full_text_read": "已读全文"}[s["access_status"]]
        out.extend([f"### {s['id']} · {s['title']}", "", f"[{s['author']}]({s['url']})；{type_label}；出版：{s['published']}；访问：{s['accessed']}；{access_label}。", "",
                    f"范围：{s['scope']}", "", f"限制：{s['limitations']}", ""])
        for e in s["evidence"]:
            out.append(f"- {e['id']}：{e['locator']}。支持：{e['supports']} 限制：{e['limits']}")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def render(lib):
    dest = safe_path(lib["root"], "HANDBOOK.md")
    if dest.exists():
        require(dest.read_text(encoding="utf-8").startswith(GENERATED + "\n"), "refusing to overwrite a hand-edited handbook without generated marker")
    dest.write_text(handbook(lib), encoding="utf-8", newline="\n")
    return {"rendered": str(dest)}


def main():
    # Windows terminals may otherwise corrupt Chinese queries and status output.
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="Knowledge directory; defaults to this project")
    sub = parser.add_subparsers(dest="command", required=True)
    for command in ("status", "check", "render"):
        sub.add_parser(command)
    find = sub.add_parser("search")
    find.add_argument("query")
    find.add_argument("--purpose", choices=["learn", "video"], default="learn")
    find.add_argument("--limit", type=int, choices=range(1, 21), default=5)
    args = parser.parse_args()
    try:
        lib = load_library(args.root)
        report = validate(lib)
        if args.command == "check":
            output = {"ok": True, **report}
        elif args.command == "status":
            output = status(lib)
        elif args.command == "render":
            output = render(lib)
        else:
            output = {"results": search(lib, args.query, args.purpose, args.limit),
                      "notice": "候选仅用于知识查询；必须再核对情境和视频证据。" if args.purpose == "learn" else "v1 未启用任何自动视频建议。"}
        print(json.dumps(output, ensure_ascii=False, indent=2))
        return 0
    except (InvalidKnowledge, OSError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())

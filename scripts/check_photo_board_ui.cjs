// Run against an isolated PHOTO_ROUTE_DATA_DIR populated by the evidence importer.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE_PATH || 'playwright')
const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')

async function main() {
  const output = process.env.PHOTO_QA_OUTPUT || path.resolve(__dirname, '../backend/data/photo_routes/qa/screenshots')
  await fs.mkdir(output, { recursive: true })
  const browser = await chromium.launch({ headless: true })
  try {
    const baseURL = process.env.PHOTO_QA_URL || 'http://127.0.0.1:5173'
    const context = await browser.newContext({ baseURL, viewport: { width: 1440, height: 1000 }, hasTouch: true })
    const page = await context.newPage(), errors = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(process.env.PHOTO_QA_URL || 'http://127.0.0.1:5173')
    await page.getByRole('button', { name: '照片线路', exact: true }).click()
    await page.locator('.photo-wood-wall').waitFor()
    const drafts = await page.request.get('/api/photo-routes/drafts').then(r => r.json())
    const blue = drafts.find(d => d.color === '蓝色'), yellow = drafts.find(d => d.color === '黄色')
    assert.ok(blue && yellow, 'two evidence drafts must be loaded before this check')
    const picker = page.locator('.photo-draft-picker select')
    await picker.selectOption(blue.id)
    await page.waitForFunction(() => document.querySelectorAll('.photo-wall-object').length === 10)
    await page.locator('.photo-wall-object image').first().evaluate(image => new Promise((resolve, reject) => { const probe = new Image(); probe.onload = resolve; probe.onerror = reject; probe.src = image.getAttribute('href') }))
    assert.equal(await page.locator('.photo-reference-holes circle').count(), 600)
    const surface = await page.locator('.photo-wood-wall').evaluate(el => { const style = getComputedStyle(el), r = el.getBoundingClientRect(); return { border: style.borderWidth, shadow: style.boxShadow, ratio: r.width/r.height } })
    assert.equal(surface.border, '0px'); assert.equal(surface.shadow, 'none'); assert.ok(Math.abs(surface.ratio - 6200/4100) < .001)
    for (const width of [1440, 1024, 390]) {
      await page.setViewportSize({ width, height: 1000 })
      await page.getByRole('button', { name: '看全板', exact: true }).click()
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `overflow at ${width}`)
      await page.screenshot({ path: path.join(output, `blue-${width}.png`), fullPage: true })
    }
    // Real two-finger browser input must zoom without editing any object.
    const client = await context.newCDPSession(page)
    const viewport = await page.locator('.photo-wall-viewport').boundingBox()
    const cx = viewport.x + viewport.width/2, cy = viewport.y + viewport.height/2
    await client.send('Input.dispatchTouchEvent', { type:'touchStart', touchPoints:[{x:cx-35,y:cy,id:1},{x:cx+35,y:cy,id:2}] })
    await client.send('Input.dispatchTouchEvent', { type:'touchMove', touchPoints:[{x:cx-80,y:cy,id:1},{x:cx+80,y:cy,id:2}] })
    await client.send('Input.dispatchTouchEvent', { type:'touchEnd', touchPoints:[] })
    await page.waitForFunction(() => Number(document.querySelector('.photo-zoom-value').textContent.replace('%','')) > 100)
    const zoom = await page.locator('.photo-zoom-value').innerText()
    await page.getByRole('button', { name:'看全板', exact:true }).click()
    const zoomOnly = await page.request.get(`/api/photo-routes/drafts/${blue.id}`).then(r => r.json())
    assert.deepEqual(zoomOnly.objects, blue.objects)
    await picker.selectOption(yellow.id)
    await page.waitForFunction(() => document.querySelectorAll('.photo-wall-object').length === 12)
    await page.setViewportSize({ width:1440, height:1000 })
    await page.screenshot({path:path.join(output,'yellow-1440.png'),fullPage:true})
    await page.getByRole('button',{name:'编辑',exact:true}).click()
    const object = page.locator('[data-object-id="object-01"]')
    const rect = await object.boundingBox()
    await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2)
    await page.mouse.down(); await page.mouse.move(rect.x+rect.width/2+35,rect.y+rect.height/2+20,{steps:6}); await page.mouse.up()
    await page.waitForFunction(() => document.querySelector('.photo-save-status').textContent === '已保存')
    const moved = await page.request.get(`/api/photo-routes/drafts/${yellow.id}`).then(r=>r.json())
    assert.ok(moved.version>yellow.version)
    assert.ok(moved.objects[0].center_x_mm>yellow.objects[0].center_x_mm)
    // Inspector changes, history and source-view switching use the same saved objects.
    await page.getByLabel('旋转（度）',{exact:true}).fill('10')
    await page.getByLabel('旋转（度）',{exact:true}).press('Tab')
    await page.getByLabel('起点',{exact:true}).check()
    await page.getByRole('button',{name:'撤销',exact:true}).click()
    assert.equal(await page.getByLabel('起点',{exact:true}).isChecked(),false)
    await page.getByRole('button',{name:'重做',exact:true}).click()
    assert.equal(await page.getByLabel('起点',{exact:true}).isChecked(),true)
    await page.getByRole('button',{name:'保存草稿',exact:true}).click()
    await page.locator('.photo-save-status.is-saved').waitFor()
    const transformed = await page.request.get(`/api/photo-routes/drafts/${yellow.id}`).then(r=>r.json())
    assert.equal(transformed.objects[0].rotation_deg,10)
    assert.deepEqual(transformed.objects[0].roles,['start'])
    await page.getByRole('button',{name:'原图对照',exact:true}).click()
    await page.getByAltText('线路原始照片').evaluate(img=>img.complete ? Promise.resolve() : new Promise(r=>{img.onload=r}))
    await page.getByRole('button',{name:'净化墙面',exact:true}).click()
    assert.equal(await page.locator('.photo-reference-view svg image').count(),13)
    await page.getByRole('button',{name:'电子岩板',exact:true}).click()
    // A separate browser session sees the saved geometry.
    const other = await browser.newContext({ baseURL })
    const otherPage = await other.newPage()
    await otherPage.goto('http://127.0.0.1:5173')
    const reopened = await otherPage.request.get(`/api/photo-routes/drafts/${yellow.id}`).then(r=>r.json())
    assert.deepEqual(reopened.objects,transformed.objects); await other.close()
    // Lease failure keeps the local change and allows explicit retry.
    await page.route(`**/api/photo-routes/drafts/${yellow.id}`, async route => {
      if (route.request().method() === 'PUT') { await route.fulfill({ status:423, contentType:'application/json', body:JSON.stringify({detail:'测试编辑权失效'}) }); await page.unroute(`**/api/photo-routes/drafts/${yellow.id}`) }
      else await route.continue()
    })
    await page.getByLabel('名称',{exact:true}).fill('黄色线路 · 恢复保存检查')
    // Do not blur: two seconds after typing must be enough to attempt a save.
    await page.locator('.photo-save-status.is-lease').waitFor()
    assert.ok(await page.evaluate(id => Boolean(localStorage.getItem(`photo-route:owner:${id}`)),yellow.id))
    await page.getByRole('button',{name:'重试保存',exact:true}).click()
    await page.locator('.photo-save-status.is-saved').waitFor()
    // Simulate another device saving before this tab, then ensure 409 never overwrites it.
    const latest = await page.request.get(`/api/photo-routes/drafts/${yellow.id}`).then(r=>r.json())
    await page.request.put(`/api/photo-routes/drafts/${yellow.id}`,{data:{expected_version:latest.version,name:'另一设备版本',color:latest.color,original_grade:latest.original_grade,notes:latest.notes,objects:latest.objects}})
    await page.getByLabel('名称',{exact:true}).fill('本地待保存副本'); await page.getByLabel('名称',{exact:true}).press('Tab')
    await page.locator('.photo-save-status.is-conflict').waitFor()
    const server = await page.request.get(`/api/photo-routes/drafts/${yellow.id}`).then(r=>r.json())
    assert.equal(server.name,'另一设备版本')
    page.on('dialog', dialog=>dialog.accept())
    await page.reload(); await page.getByRole('button',{name:'照片线路',exact:true}).click()
    await page.locator('.photo-save-status.is-conflict').waitFor()
    assert.equal(await page.getByLabel('名称',{exact:true}).inputValue(),'本地待保存副本')
    assert.deepEqual(errors,[])
    await fs.writeFile(path.join(output,'results.json'),JSON.stringify({viewports:[1440,1024,390],holes:600,pinchZoom:zoom,dragSaved:true,crossSession:true,leaseRecovery:true,conflictRecovery:true,browserErrors:errors},null,2))
    console.log('Photo board browser checks passed; screenshots: '+output)
  } finally { await browser.close() }
}
main().catch(error=>{console.error(error);process.exitCode=1})
